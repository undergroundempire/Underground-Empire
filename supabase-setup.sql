-- Run this in Supabase Dashboard > SQL Editor.
-- Create a media table. Enable Row Level Security.
create table if not exists public.media (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('songs','videos','photos')),
  title text not null,
  artist text default 'Underground Empire',
  file_url text not null,
  cover_url text,
  file_name text,
  created_at timestamptz not null default now()
);

alter table public.media enable row level security;

-- Public visitors can see the catalog.
create policy "Public can view media"
on public.media for select
to anon, authenticated
using (true);

-- Only authenticated users can add and delete records.
create policy "Authenticated users can add media"
on public.media for insert
to authenticated
with check (true);

create policy "Authenticated users can delete media"
on public.media for delete
to authenticated
using (true);

-- Storage bucket policy setup:
-- In Supabase Dashboard > Storage, create a PUBLIC bucket named: media
